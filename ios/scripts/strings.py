#!/usr/bin/env python3
"""Generate the iOS .strings files from the Android string resources, so both
apps share one wording in English and Arabic. Run after changing
android/app/src/main/res/values*/strings.xml."""
import pathlib, re, xml.etree.ElementTree as ET

root = pathlib.Path(__file__).resolve().parents[2]
res = root / "android/app/src/main/res"
out = root / "ios/AmanfoldKit/Sources/AmanfoldKit/Resources"

def load(p):
    d = {}
    for s in ET.parse(p).getroot().findall("string"):
        v = "".join(s.itertext())
        v = v.replace("\\'", "'").replace('\\"', '"')
        v = re.sub(r"%(\d+)\$s", r"%\1$@", v)
        v = re.sub(r"%(\d+)\$d", r"%\1$ld", v)
        d[s.get("name")] = v
    return d

# Text only the iOS app needs.
IOS_EN = {
    "ios_autofill_steps": "To fill passwords in Safari and apps, open Settings, then General, AutoFill & Passwords, and turn on Amanfold.",
    "ios_open_settings": "Open Settings",
    "ios_language_hint": "Choose the language in the phone's Settings for Amanfold.",
    "ios_face_id_reason": "Unlock your Amanfold vault",
    "ios_sign_out_confirm": "Sign out of this iPhone? Your vault stays on the server; you will need your Secret Key to sign in again.",
}
IOS_AR = {
    "ios_autofill_steps": "لتعبئة كلمات المرور في سفاري والتطبيقات، افتح الإعدادات ثم عام ثم التعبئة التلقائية وكلمات المرور، وفعّل أمان فولد.",
    "ios_open_settings": "فتح الإعدادات",
    "ios_language_hint": "اختر لغة أمان فولد من إعدادات الهاتف.",
    "ios_face_id_reason": "فتح خزنة أمان فولد",
    "ios_sign_out_confirm": "تسجيل الخروج من هذا الآيفون؟ تبقى خزنتك على الخادم، وستحتاج إلى المفتاح السري لتسجيل الدخول مجددًا.",
}
assert IOS_EN.keys() == IOS_AR.keys()
en = {**load(res / "values/strings.xml"), **IOS_EN}
langs = {"en": en, "ar": {**en, **load(res / "values-ar/strings.xml"), **IOS_AR}}
for lang, d in langs.items():
    lines = ["/* Generated by ios/scripts/strings.py from the Android strings. Do not edit. */"]
    for k, v in d.items():
        v = v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        lines.append(f'"{k}" = "{v}";')
    d_out = out / f"{lang}.lproj"
    d_out.mkdir(parents=True, exist_ok=True)
    (d_out / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(lang, len(d))
